#!/usr/bin/env bash
# test-interactive-startup.sh — Smoke-test zsh and tmux startup parsing
set -euo pipefail

DOTFILES_DIR="${1:-$(cd "$(dirname "$0")/.." && pwd)}"
TMP_HOME=$(mktemp -d)
trap 'rm -rf "$TMP_HOME"' EXIT
export XDG_CONFIG_HOME="$TMP_HOME/.config" XDG_DATA_HOME="$TMP_HOME/.local/share"
export XDG_STATE_HOME="$TMP_HOME/.local/state" XDG_CACHE_HOME="$TMP_HOME/.cache"

render_template() {
  local src="$1" dest="$2" is_wsl="${3:-false}"
  awk -v is_wsl="$is_wsl" -v source_dir="$DOTFILES_DIR" '
    function emit(line) {
      gsub(/{{ \.chezmoi\.sourceDir }}/, source_dir, line)
      gsub(/{{ \.chezmoi\.sourceFile }}/, source_dir, line)
      gsub(/{{ \.sessionizer_dirs \| quote }}/, "\"~/Code ~/Scripts\"", line)
      gsub(/{{ \.sessionizer_dirs }}/, "~/Code ~/Scripts", line)
      gsub(/{{ \.email }}/, "test@example.com", line)
      gsub(/{{ \.name }}/, "Test User", line)
      print line
    }
    /^[[:space:]]*{{-? if \.is_wsl }}[[:space:]]*$/ { stack[++depth] = include; include = include && (is_wsl == "true"); next }
    /^[[:space:]]*{{ if not \.is_wsl }}[[:space:]]*$/ { stack[++depth] = include; include = include && (is_wsl != "true"); next }
    /^[[:space:]]*{{-? else }}[[:space:]]*$/ { parent = stack[depth]; include = parent && !include; next }
    /^[[:space:]]*{{-? end }}[[:space:]]*$/ { include = stack[depth--]; next }
    BEGIN { include = 1; depth = 0 }
    { if (include) emit($0) }
  ' "$src" >"$dest"
}

mkdir -p "$TMP_HOME/.oh-my-zsh"
printf '# test stub
' >"$TMP_HOME/.oh-my-zsh/oh-my-zsh.sh"
cat >"$TMP_HOME/.zshenv" <<'EOF'
complete() { true; }
EOF

render_template "$DOTFILES_DIR/dot_zshrc.tmpl" "$TMP_HOME/.zshrc" false
render_template "$DOTFILES_DIR/dot_tmux.conf.tmpl" "$TMP_HOME/.tmux.conf" false

if command -v zsh >/dev/null 2>&1; then
  wait_for_cache() {
    local previous="${1:-}" current
    for _ in {1..100}; do
      current="$(stat -c '%i' "$TMP_HOME/.zshrc.zwc" 2>/dev/null || true)"
      if [[ -n "$current" && "$current" != "$previous" ]] &&
        ! compgen -G "$TMP_HOME/.zshrc-compile.*" >/dev/null; then
        return 0
      fi
      sleep 0.02
    done
    printf 'Zsh startup did not publish and clean up its compiled cache\n' >&2
    return 1
  }
  HOME="$TMP_HOME" ZDOTDIR="$TMP_HOME" zsh -dfn "$TMP_HOME/.zshrc"
  HOME="$TMP_HOME" ZDOTDIR="$TMP_HOME" zsh -dfi -c 'source "$HOME/.zshrc"'
  wait_for_cache
  [[ "$(stat -c '%a' "$TMP_HOME/.zshrc.zwc")" == 600 ]]
  HOME="$TMP_HOME" ZDOTDIR="$TMP_HOME" zsh -df -c 'zcompile -t "$HOME/.zshrc.zwc"' >/dev/null

  # Fresh caches are reused; old caches rebuild after ordinary config edits.
  cache_inode="$(stat -c '%i' "$TMP_HOME/.zshrc.zwc")"
  HOME="$TMP_HOME" ZDOTDIR="$TMP_HOME" zsh -dfi -c 'source "$HOME/.zshrc"'
  [[ "$(stat -c '%i' "$TMP_HOME/.zshrc.zwc")" == "$cache_inode" ]]
  printf '\nexport ZSH_TEST_COMPILED=ready\n' >>"$TMP_HOME/.zshrc"
  touch -d '1 minute ago' "$TMP_HOME/.zshrc.zwc"
  HOME="$TMP_HOME" ZDOTDIR="$TMP_HOME" zsh -dfi -c 'source "$HOME/.zshrc"'
  wait_for_cache "$cache_inode"

  # Prove source uses the generated bytecode when its timestamp is current.
  cp -p "$TMP_HOME/.zshrc" "$TMP_HOME/original.zshrc"
  printf 'export ZSH_TEST_COMPILED=not_the_cache\n' >"$TMP_HOME/.zshrc"
  touch -r "$TMP_HOME/original.zshrc" "$TMP_HOME/.zshrc"
  HOME="$TMP_HOME" ZDOTDIR="$TMP_HOME" zsh -df -c 'source "$HOME/.zshrc"; [[ "$ZSH_TEST_COMPILED" == ready ]]'
  mv "$TMP_HOME/original.zshrc" "$TMP_HOME/.zshrc"

  # Concurrent cold starts publish complete caches without temporary-file leaks.
  rm "$TMP_HOME/.zshrc.zwc"
  mkdir -p "$TMP_HOME/bin"
  cat >"$TMP_HOME/bin/mktemp" <<'EOF'
#!/bin/sh
directory=$(/usr/bin/mktemp "$@") || exit
touch "$HOME/cache-start.$$"
attempt=0
while [ "$attempt" -lt 200 ]; do
  if [ "$(find "$HOME" -maxdepth 1 -name 'cache-start.*' -printf . | wc -c)" -eq 4 ]; then
    printf '%s\n' "$directory"
    exit 0
  fi
  attempt=$((attempt + 1))
  sleep 0.01
done
exit 1
EOF
  chmod +x "$TMP_HOME/bin/mktemp"
  startup_pids=()
  for _ in {1..4}; do
    HOME="$TMP_HOME" ZDOTDIR="$TMP_HOME" PATH="$TMP_HOME/bin:$PATH" \
      zsh -dfi -c 'source "$HOME/.zshrc"' &
    startup_pids+=("$!")
  done
  for pid in "${startup_pids[@]}"; do
    wait "$pid"
  done
  wait_for_cache
  [[ "$(find "$TMP_HOME" -maxdepth 1 -name 'cache-start.*' -printf . | wc -c)" -eq 4 ]]
  rm "$TMP_HOME/bin/mktemp"
  HOME="$TMP_HOME" ZDOTDIR="$TMP_HOME" zsh -df -c 'zcompile -t "$HOME/.zshrc.zwc"' >/dev/null

  # A compiler I/O failure leaves the previous cache intact and cleans staging.
  cat >"$TMP_HOME/bin/mktemp" <<'EOF'
#!/bin/sh
directory=$(/usr/bin/mktemp "$@") || exit
chmod 500 "$directory"
printf '%s\n' "$directory"
touch "$HOME/compile-attempted"
EOF
  chmod +x "$TMP_HOME/bin/mktemp"
  touch -d '1 minute ago' "$TMP_HOME/.zshrc.zwc"
  cache_before="$(sha256sum "$TMP_HOME/.zshrc.zwc")"
  HOME="$TMP_HOME" ZDOTDIR="$TMP_HOME" PATH="$TMP_HOME/bin:$PATH" \
    zsh -dfi -c 'source "$HOME/.zshrc"'
  for _ in {1..100}; do
    if [[ -e "$TMP_HOME/compile-attempted" ]] &&
      ! compgen -G "$TMP_HOME/.zshrc-compile.*" >/dev/null; then
      break
    fi
    sleep 0.02
  done
  [[ -e "$TMP_HOME/compile-attempted" && "$(sha256sum "$TMP_HOME/.zshrc.zwc")" == "$cache_before" ]]
  ! compgen -G "$TMP_HOME/.zshrc-compile.*" >/dev/null
  rm "$TMP_HOME/bin/mktemp"

  mv "$TMP_HOME/.zshrc.zwc" "$TMP_HOME/external.zwc"
  touch -d '1 minute ago' "$TMP_HOME/external.zwc"
  ln -s "$TMP_HOME/external.zwc" "$TMP_HOME/.zshrc.zwc"
  external_before="$(sha256sum "$TMP_HOME/external.zwc")"
  HOME="$TMP_HOME" ZDOTDIR="$TMP_HOME" zsh -dfi -c 'source "$HOME/.zshrc"'
  [[ -L "$TMP_HOME/.zshrc.zwc" && "$(sha256sum "$TMP_HOME/external.zwc")" == "$external_before" ]]
else
  echo "zsh not installed; skipping zsh startup"
fi

if command -v tmux >/dev/null 2>&1; then
  tmux -L dotfiles-startup-test -f "$TMP_HOME/.tmux.conf" start-server \; source-file "$TMP_HOME/.tmux.conf" \; kill-server
else
  echo "tmux not installed; skipping tmux startup"
fi

echo "interactive startup smoke passed"
