#!/usr/bin/python3
"""Validate section facts and generate install.sh's pre-checkout Bash registry."""

import argparse
import configparser
import json
from pathlib import Path
import re
import shlex

BEGIN = "# BEGIN GENERATED SECTION REGISTRY"
END = "# END GENERATED SECTION REGISTRY"


def registry(root):
    entries = json.loads((root / "scripts/sections.json").read_text())
    orders = set()
    for name, entry in entries.items():
        if not re.fullmatch(r"[a-z][a-z0-9_-]*", name):
            raise ValueError(f"Invalid section: {name}")
        if entry["order"] in orders:
            raise ValueError(f"Duplicate section order: {entry['order']}")
        orders.add(entry["order"])
        for field in ("manifest", "commands", "dependencies", "shared_inputs"):
            if not isinstance(entry[field], list):
                raise ValueError(f"{name}.{field} must be a list")
        if not (root / entry["script"]).is_file():
            raise ValueError(f"Missing section script: {entry['script']}")
        for dependency in entry["dependencies"]:
            if (
                dependency not in entries
                or entries[dependency]["order"] >= entry["order"]
            ):
                raise ValueError(
                    f"{name}: dependency must precede section: {dependency}"
                )
    return dict(sorted(entries.items(), key=lambda item: item[1]["order"]))


def profiles(root, entries):
    result = {}
    for path in sorted((root / "profiles").glob("*.conf")):
        config = configparser.ConfigParser(interpolation=None)
        config.read_string("[profile]\n" + path.read_text())
        profile = config["profile"]
        name = profile["name"]
        if name != path.stem or not re.fullmatch(r"[a-z][a-z0-9_-]*", name):
            raise ValueError(f"Invalid profile name: {path}")
        sections = profile["sections"].split(",")
        if len(set(sections)) != len(sections) or any(
            section not in entries for section in sections
        ):
            raise ValueError(f"Invalid profile sections: {path}")
        if sections != [section for section in entries if section in sections]:
            raise ValueError(f"Profile must follow registry order: {path}")
        for section in sections:
            if not set(entries[section]["dependencies"]) <= set(sections):
                raise ValueError(f"Missing profile dependencies: {path}: {section}")
        result[name] = ",".join(sections)
    if not result:
        raise ValueError("No profiles found")
    return result


def shell_block(root):
    entries = registry(root)
    lines = [
        BEGIN,
        "# Generated by scripts/section-registry.py; do not edit by hand.",
        "SECTION_ORDER=(" + " ".join(entries) + ")",
        "declare -A BUILTIN_PROFILES=(",
    ]
    lines.extend(
        f'  [{name}]="{sections}"' for name, sections in profiles(root, entries).items()
    )
    lines.extend([")", "declare -A PROFILE_SECTION_DEPENDENCIES=("])
    lines.extend(
        f"  [{name}]={shlex.quote(' '.join(entry['dependencies']))}"
        for name, entry in entries.items()
        if entry["dependencies"]
    )
    lines.extend([")", END])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source", type=Path, default=Path(__file__).resolve().parent.parent
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()
    generated = shell_block(args.source)
    if not (args.check or args.write):
        print(generated)
        return
    installer = args.source / "scripts/install.sh"
    current = installer.read_text()
    before, rest = current.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    updated = before + generated + after
    if args.write:
        installer.write_text(updated)
    elif updated != current:
        raise ValueError(
            "Standalone registry is stale; run /usr/bin/python3 scripts/section-registry.py --write"
        )


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, KeyError) as error:
        raise SystemExit(str(error)) from error
